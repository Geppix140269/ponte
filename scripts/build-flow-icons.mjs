// Generates the inline-markup module for the Ponte Flow icon library.
//
//   node scripts/build-flow-icons.mjs
//
// The handoff ships 126 SVG files and a registry that returns *paths*, leaving
// the delivery mechanism to the implementation. This is that decision, made
// once and recorded here.
//
// Why inline, and why generated:
//
//   - `currentColor` and the optical stroke both have to be set on the <svg>
//     root at render time, per rendered size. A fetched <img> cannot inherit
//     colour, and a sprite makes per-size stroke awkward.
//   - Pasting SVG markup into route files is exactly what the handoff forbids,
//     and it is how two copies of an icon start to disagree.
//   - The repository has no SVG loader in its build, and adding one (svgr, a
//     webpack rule) to ship 50 KB of line art is a larger change than the art.
//
// So this script reads the vendored assets and writes their *inner* markup into
// one generated module keyed by asset path. `PonteIcon` supplies the <svg> root
// itself, which is what lets it set viewBox, stroke width and colour correctly.
//
// The module is imported only by a server component, so the markup is rendered
// to HTML on the server and none of it reaches the client bundle.
//
// Regenerate after any asset change. The output is committed so a build never
// depends on this script having been run.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, posix } from "node:path";

const ROOT = "design-system/ponte-flow";
const REGISTRY = join(ROOT, "registry", "ponte-flow-registry.json");
const OUT = join(ROOT, "generated", "flow-icon-markup.ts");

if (!existsSync(REGISTRY)) {
  console.error(`No registry at ${REGISTRY}`);
  process.exit(1);
}

const icons = JSON.parse(readFileSync(REGISTRY, "utf8"));
const list = Array.isArray(icons) ? icons : (icons.icons ?? []);
if (list.length === 0) {
  console.error("Registry contained no icons.");
  process.exit(1);
}

/** The children of the <svg> root, with the root's own attributes dropped. */
function innerOf(file) {
  const raw = readFileSync(file, "utf8");
  const open = raw.indexOf(">");
  const close = raw.lastIndexOf("</svg>");
  if (open < 0 || close < 0) throw new Error(`${file} is not a single <svg> document`);

  const inner = raw.slice(open + 1, close).trim();

  // The handoff's own validation guarantees these are absent. Re-check here,
  // because this script is what would carry such a thing into the product.
  for (const banned of ["<title", "<desc", "<image", "clip-path", "mask=", "font-family"]) {
    if (inner.includes(banned)) throw new Error(`${file} contains ${banned}`);
  }
  if (/(?:fill|stroke)="(?!none|currentColor)[^"]+"/.test(inner)) {
    throw new Error(`${file} hardcodes a colour; every asset must use currentColor`);
  }
  return inner;
}

const entries = [];
const seen = new Set();
let missing = 0;

for (const icon of list) {
  for (const path of [icon.standardAsset, icon.reducedAsset]) {
    if (!path || seen.has(path)) continue;
    seen.add(path);
    const file = join(ROOT, path);
    if (!existsSync(file)) {
      console.error(`MISSING ${path} (referenced by ${icon.key})`);
      missing++;
      continue;
    }
    entries.push([posix.normalize(path), innerOf(file)]);
  }
}

if (missing > 0) {
  console.error(`${missing} registry asset(s) could not be resolved.`);
  process.exit(1);
}

entries.sort((a, b) => (a[0] < b[0] ? -1 : 1));

const body = entries
  .map(([path, inner]) => `  ${JSON.stringify(path)}: ${JSON.stringify(inner)},`)
  .join("\n");

const out = `// GENERATED by scripts/build-flow-icons.mjs. Do not edit.
//
// The inner markup of every Ponte Flow asset, keyed by its registry path. The
// <svg> root is supplied by PonteIcon, which is what allows the optical stroke
// and currentColor to be applied per rendered size.

export const FLOW_ICON_MARKUP: Record<string, string> = {
${body}
};
`;

writeFileSync(OUT, out);

// The key union and the label-required set, as literal types.
//
// The shipped registry annotates its array as `PonteIcon[]`, which widens every
// key to `string`, so a typo in a route would compile. Generating the union is
// what makes "accept only registered semantic keys" a compile error rather than
// a runtime throw, and what makes the accessibility rule enforceable: the 14
// keys whose icon carries the meaning alone require a label, and the component
// types that requirement rather than trusting a reviewer to notice.
const KEYS_OUT = join(ROOT, "generated", "flow-icon-keys.ts");
const keys = list.map((i) => i.key).sort();
const labelled = list.filter((i) => i.accessibilityLabelRequired).map((i) => i.key).sort();

for (const key of keys) {
  if (/verified|trusted|safe|score|rating/i.test(key)) {
    console.error(`Registry key "${key}" claims a trust state the product does not have.`);
    process.exit(1);
  }
}

const union = (values) =>
  values.length === 0
    ? "never"
    : values.map((v) => "\n  | " + JSON.stringify(v)).join("");

writeFileSync(
  KEYS_OUT,
  `// GENERATED by scripts/build-flow-icons.mjs. Do not edit.

/** Every registered Ponte Flow semantic key. A key not in this union does not exist. */
export type FlowIconKey =${union(keys)};

/**
 * The keys whose icon is the only carrier of its meaning. PonteIcon requires an
 * explicit label for these and forbids one for the rest, which is the
 * accessibility contract in documentation/accessibility.md expressed as types.
 */
export type FlowLabelledKey =${union(labelled)};

export const FLOW_LABELLED_KEYS: readonly FlowLabelledKey[] = [
${labelled.map((k) => "  " + JSON.stringify(k) + ",").join("\n")}
];
`,
);

console.log(`Wrote ${OUT}: ${entries.length} assets, ${(out.length / 1024).toFixed(1)} KB.`);
console.log(`Wrote ${KEYS_OUT}: ${keys.length} keys, ${labelled.length} requiring a label.`);
